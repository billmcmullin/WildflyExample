CREATE TABLE calendar_preferences (
    username VARCHAR(100) PRIMARY KEY REFERENCES user_calendars(username),
    zone_id VARCHAR(100) NOT NULL,
    week_start INTEGER NOT NULL CHECK (week_start IN (1, 7)),
    default_view VARCHAR(16) NOT NULL CHECK (default_view IN ('month', 'agenda'))
);

CREATE TABLE calendar_events (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY (START WITH 1) PRIMARY KEY,
    username VARCHAR(100) NOT NULL REFERENCES user_calendars(username),
    event_uid VARCHAR(255) NOT NULL,
    title VARCHAR(200) NOT NULL,
    description VARCHAR(5000) NOT NULL,
    start_local TIMESTAMP NOT NULL,
    end_local TIMESTAMP NOT NULL,
    zone_id VARCHAR(100) NOT NULL,
    all_day BOOLEAN NOT NULL,
    recurrence_rule VARCHAR(256) NOT NULL,
    reminder_minutes INTEGER NOT NULL,
    version BIGINT DEFAULT 1 NOT NULL,
    UNIQUE (username, event_uid)
);
CREATE INDEX calendar_events_owner_start ON calendar_events(username, start_local);

CREATE TABLE calendar_exceptions (
    event_id BIGINT NOT NULL REFERENCES calendar_events(id) ON DELETE CASCADE,
    occurrence_start TIMESTAMP NOT NULL,
    PRIMARY KEY (event_id, occurrence_start)
);

CREATE TABLE calendar_audit (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY (START WITH 1) PRIMARY KEY,
    username VARCHAR(100) NOT NULL REFERENCES user_calendars(username),
    event_id BIGINT NOT NULL,
    action VARCHAR(32) NOT NULL,
    title VARCHAR(200) NOT NULL,
    details VARCHAR(12000) NOT NULL,
    changed_ms BIGINT NOT NULL
);
CREATE INDEX calendar_audit_owner_time ON calendar_audit(username, changed_ms);

CREATE TABLE calendar_notifications (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY (START WITH 1) PRIMARY KEY,
    event_id BIGINT NOT NULL REFERENCES calendar_events(id) ON DELETE CASCADE,
    username VARCHAR(100) NOT NULL REFERENCES user_calendars(username),
    occurrence_start TIMESTAMP NOT NULL,
    title VARCHAR(200) NOT NULL,
    due_ms BIGINT NOT NULL,
    is_read BOOLEAN DEFAULT FALSE NOT NULL,
    UNIQUE (event_id, occurrence_start)
);